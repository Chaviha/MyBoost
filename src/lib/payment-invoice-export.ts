/** Printable / downloadable invoices, payment receipts, and account statements (HTML + browser print/PDF). */

import type { Invoice, LedgerEntry, PaymentLineItem } from "./types";

export type DocBusiness = {
  business_name: string;
  phone?: string;
  email?: string;
  region?: string;
};

export type PaymentReceiptDoc = {
  receipt_number: string;
  entry_id?: string;
  customer_name: string;
  amount: number;
  date: string;
  description?: string;
  method?: string;
  invoice_id?: string;
  payment_kind?: "invoice" | "direct";
  line_items?: PaymentLineItem[];
  balance_after?: number;
  status?: string;
};

function esc(s: string): string {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function money(n: number): string {
  return `KSh ${Number(n || 0).toLocaleString("en-KE", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })}`;
}

function formatDate(iso: string): string {
  try {
    return new Date(iso).toLocaleDateString("en-KE", {
      year: "numeric",
      month: "short",
      day: "numeric",
    });
  } catch {
    return iso || "—";
  }
}

function formatDateTime(iso: string): string {
  try {
    return new Date(iso).toLocaleString("en-KE", {
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return iso || "—";
  }
}

