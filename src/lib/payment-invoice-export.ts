export function buildPaymentReceiptHtml(
  receipt: PaymentReceiptDoc,
  business: DocBusiness,
): string {
  const items = receipt.line_items || [];
  const kindLabel =
    receipt.payment_kind === "invoice"
      ? "Invoice-linked payment"
      : "Direct payment";
  const body = `
  <header>
    <div>
      <h1>Payment Receipt</h1>
      <p class="meta">${esc(receipt.receipt_number)}</p>
    </div>
    <div style="text-align:right">
      <p style="margin:0;font-weight:600">${esc(business.business_name)}</p>
      ${business.phone ? `<p class="meta" style="margin:2px 0 0">${esc(business.phone)}</p>` : ""}
      ${business.email ? `<p class="meta" style="margin:2px 0 0">${esc(business.email)}</p>` : ""}
    </div>
  </header>

  <div style="display:flex;justify-content:space-between;gap:16px;flex-wrap:wrap;margin-bottom:8px">
    <div>
      <p class="meta" style="margin:0">Received from</p>
      <p style="margin:4px 0 0;font-weight:600">${esc(receipt.customer_name)}</p>
      <p class="meta" style="margin:4px 0 0">${esc(kindLabel)}</p>
      ${receipt.invoice_id ? `<p class="meta" style="margin:4px 0 0">Invoice ${esc(receipt.invoice_id)}</p>` : ""}
      ${receipt.method ? `<p class="meta" style="margin:4px 0 0">Method: ${esc(receipt.method)}</p>` : ""}
    </div>
    <div style="text-align:right">
      <p class="meta" style="margin:0">${esc(formatDateTime(receipt.date))}</p>
      ${receipt.status ? `<p class="meta" style="margin:4px 0 0">Status: ${esc(receipt.status)}</p>` : ""}
    </div>
  </div>

  ${
    items.length
      ? `<table>
    <thead>
      <tr>
        <th>Description</th>
        <th class="num">Qty</th>
        <th class="num">Rate</th>
        <th class="num">Amount</th>
      </tr>
    </thead>
    <tbody>
      ${lineRows(items)}
    </tbody>
  </table>`
      : ""
  }

  <div class="totals">
    <div class="row grand"><span>Amount paid</span><span>${esc(money(receipt.amount))}</span></div>
    ${
      receipt.balance_after !== undefined
        ? `<div class="row"><span class="muted">Tab balance after</span><span>${esc(money(receipt.balance_after))}</span></div>`
        : ""
    }
  </div>
  ${receipt.description ? `<p class="muted" style="margin-top:16px">${esc(receipt.description)}</p>` : ""}
`;
  return shell(`Receipt ${receipt.receipt_number} — ${receipt.customer_name}`, body);
}

function downloadHtml(html: string, filename: string): void {
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

function printHtml(html: string): void {
  const iframe = document.createElement("iframe");
  iframe.style.position = "fixed";
  iframe.style.right = "0";
  iframe.style.bottom = "0";
  iframe.style.width = "0";
  iframe.style.height = "0";
  iframe.style.border = "0";
  document.body.appendChild(iframe);
  const doc = iframe.contentDocument || iframe.contentWindow?.document;
  if (!doc) {
    document.body.removeChild(iframe);
    return;
  }
  doc.open();
  doc.write(html);
  doc.close();
  setTimeout(() => {
    iframe.contentWindow?.focus();
    iframe.contentWindow?.print();
    setTimeout(() => document.body.removeChild(iframe), 1000);
  }, 250);
}

export function downloadInvoiceHtml(invoice: Invoice, business: DocBusiness): void {
  const html = buildInvoiceHtml(invoice, business);
  const safeName = invoice.customer_name.replace(/\s+/g, "-") || "customer";
  downloadHtml(html, `invoice-${invoice.invoice_id}-${safeName}.html`);
}

export function printInvoice(invoice: Invoice, business: DocBusiness): void {
  printHtml(buildInvoiceHtml(invoice, business));
}

export function downloadPaymentReceiptHtml(
  receipt: PaymentReceiptDoc,
  business: DocBusiness,
): void {
  const html = buildPaymentReceiptHtml(receipt, business);
  const safe = (receipt.receipt_number || "receipt").replace(/\s+/g, "-");
  downloadHtml(html, `receipt-${safe}.html`);
}

export function printPaymentReceipt(
  receipt: PaymentReceiptDoc,
  business: DocBusiness,
): void {
  printHtml(buildPaymentReceiptHtml(receipt, business));
}
