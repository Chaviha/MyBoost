function lineRows(items: PaymentLineItem[] | undefined): string {
  if (!items?.length) {
    return `<tr><td colspan="4" style="padding:12px;color:#666">No line items</td></tr>`;
  }
  return items
    .map(
      (li) => `
    <tr>
      <td>${esc(li.description)}</td>
      <td class="num">${Number(li.qty || 0).toLocaleString("en-KE", { maximumFractionDigits: 3 })}</td>
      <td class="num">${esc(money(li.unit_price))}</td>
      <td class="num">${esc(money(li.amount))}</td>
    </tr>`,
    )
    .join("");
}

function shell(title: string, body: string): string {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>${esc(title)}</title>
  <style>${baseStyles}</style>
</head>
<body>
${body}
  <div class="actions no-print">
    <button class="primary" onclick="window.print()">Print / Save as PDF</button>
  </div>
  <footer>
    Generated by LifeBoost · ${esc(new Date().toLocaleString("en-KE"))}
    <span class="no-print"> · Use Print → Save as PDF for a PDF copy</span>
  </footer>
</body>
</html>`;
}

